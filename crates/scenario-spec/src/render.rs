//! A [`Spec`] plus prices → the overlay TOML (`config/scale-<name>.toml`)
//! and the token bootstrap config for specs with extra tokens.
//!
//! Maker and bot inventories are set in USD at the given prices (3
//! significant figures); taker inventory keeps the base profile's fixed
//! JUP / RAY / USDC amounts plus $5k of each extra token. The format is the
//! one `bootstrap/scenario/scale.py` wrote, so presets diff cleanly against
//! the overlays it generated.

use std::collections::BTreeMap;

use rust_decimal::{Decimal, RoundingStrategy};

use crate::{CATALOG, Pool, Spec, Venue};

/// USD prices by token name (USDC may be omitted: it is pegged).
pub type Prices = BTreeMap<String, Decimal>;

/// The first line of every generated overlay; the second holds the spec.
pub const HEADER: &str =
    "# Generated by `scenario overlay` (crates/scenario-spec) — do not edit by hand.";
pub const SPEC_PREFIX: &str = "# spec: ";

/// Per-bot searcher profile, so the population does not act in lockstep:
/// priority fee (lamports per cycle) and reaction latency (ms).
const BOT_PROFILES: [(u64, u64); 5] = [(0, 0), (5000, 150), (20000, 400), (0, 50), (10000, 250)];
/// (min profit USD, max trade USD, max legs), cycled per bot.
const BOT_PARAMS: [(&str, &str, i64); 5] = [
    ("0.50", "5000", 3),
    ("0.25", "2500", 3),
    ("1.00", "10000", 3),
    ("2.00", "1500", 2),
    ("0.75", "4000", 3),
];

#[derive(Debug, Clone)]
enum V {
    Int(i64),
    Float(f64),
    Str(String),
    List(Vec<V>),
    Table(Vec<(&'static str, V)>),
}

fn s(value: impl Into<String>) -> V {
    V::Str(value.into())
}

impl V {
    fn emit(&self, out: &mut String) {
        match self {
            V::Int(i) => out.push_str(&i.to_string()),
            // Debug keeps a trailing `.0` (`150.0`), as Python's str(float) does.
            V::Float(f) => out.push_str(&format!("{f:?}")),
            V::Str(text) => out.push_str(&serde_json::to_string(text).unwrap_or_default()),
            V::List(items) => {
                out.push('[');
                for (i, item) in items.iter().enumerate() {
                    if i > 0 {
                        out.push_str(", ");
                    }
                    item.emit(out);
                }
                out.push(']');
            }
            V::Table(fields) => {
                out.push_str("{ ");
                for (i, (key, value)) in fields.iter().enumerate() {
                    if i > 0 {
                        out.push_str(", ");
                    }
                    out.push_str(key);
                    out.push_str(" = ");
                    value.emit(out);
                }
                out.push_str(" }");
            }
        }
    }
}

type Row = Vec<(&'static str, V)>;

fn table(out: &mut String, name: &str, row: &Row) {
    out.push_str(&format!("[{name}]\n"));
    for (key, value) in row {
        out.push_str(key);
        out.push_str(" = ");
        value.emit(out);
        out.push('\n');
    }
    out.push('\n');
}

fn array_table(out: &mut String, name: &str, rows: &[Row]) {
    for row in rows {
        out.push_str(&format!("[[{name}]]\n"));
        for (key, value) in row {
            out.push_str(key);
            out.push_str(" = ");
            value.emit(out);
            out.push('\n');
        }
        out.push('\n');
    }
}

/// USD → token amount, 3 significant figures, as a plain decimal string.
pub fn amount(usd: Decimal, price: Decimal) -> String {
    let value = usd / price;
    value
        .round_sf_with_strategy(3, RoundingStrategy::MidpointNearestEven)
        .unwrap_or(value)
        .normalize()
        .to_string()
}

fn inventory(entries: Vec<(String, String)>) -> V {
    // Keys are token names, which Spec::check limits to the catalog.
    V::Table(
        entries
            .into_iter()
            .map(|(token, value)| (catalog_name(&token), s(value)))
            .collect(),
    )
}

fn catalog_name(token: &str) -> &'static str {
    CATALOG
        .iter()
        .find(|(name, _)| *name == token)
        .map(|(name, _)| *name)
        .unwrap_or("UNKNOWN")
}

/// A rendered overlay.
pub struct Rendered {
    pub toml: String,
    pub participants: u32,
}

/// A token's price; USDC defaults to its peg.
fn price_of(prices: &Prices, token: &str) -> Result<Decimal, String> {
    if token == "USDC" {
        return Ok(prices.get("USDC").copied().unwrap_or(Decimal::ONE));
    }
    prices
        .get(token)
        .copied()
        .filter(|p| *p > Decimal::ZERO)
        .ok_or_else(|| format!("no price for {token}"))
}

fn makers(spec: &Spec, pools: &[Pool], prices: &Prices) -> Result<Vec<Row>, String> {
    let capital = spec.capital();
    let d = Decimal::from;
    let mut rows = Vec::new();
    for pool in pools {
        let (base, quote) = (pool.base.as_str(), pool.quote.as_str());
        let (pb, pq) = (price_of(prices, base)?, price_of(prices, quote)?);
        let venue_tag = pool.venue.as_str().split('-').next().unwrap_or_default();
        let tag = format!(
            "{venue_tag}-{}{}",
            base.to_lowercase(),
            if quote == "USDC" {
                String::new()
            } else {
                format!("-{}", quote.to_lowercase())
            }
        );
        let (ladders, ranges, arbs) = spec.makers_on(pool);
        if pool.venue == Venue::Manifest {
            for k in 0..usize::from(ladders) {
                let (spread, step, level_usd, refresh) =
                    [(10, 8, 560, 5), (25, 15, 900, 10), (50, 30, 400, 15)][k];
                let mut strategy: Row = vec![
                    ("kind", s("clob-ladder")),
                    ("levels", V::Int([5, 3, 4][k])),
                    ("spread_bps", V::Int(spread)),
                    ("step_bps", V::Int(step)),
                    ("level_size", s(amount(d(level_usd) * capital, pb))),
                    ("refresh_bps", V::Int(refresh)),
                ];
                if k == 1 {
                    strategy.push(("skew_bps", V::Int(60)));
                    strategy.push(("target_base_ratio", s("0.5")));
                }
                rows.push(vec![
                    ("name", s(format!("clob-{}-{k}", base.to_lowercase()))),
                    ("venue", s(pool.venue.as_str())),
                    ("base", s(base)),
                    ("quote", s(quote)),
                    ("interval_ms", V::Int(2000 + 500 * k as i64)),
                    (
                        "inventory",
                        inventory(vec![
                            (base.to_owned(), amount(d(22000) * capital, pb)),
                            (quote.to_owned(), amount(d(20000) * capital, pq)),
                        ]),
                    ),
                    ("strategy", V::Table(strategy)),
                ]);
            }
            continue;
        }
        for k in 0..usize::from(ranges.max(arbs)) {
            if k < usize::from(ranges) {
                let (width, recenter, position) =
                    [(600, 200, 20000), (1200, 400, 15000), (2500, 800, 10000)][k];
                let deposit = d(position) * Decimal::new(8, 1) * capital;
                rows.push(vec![
                    ("name", s(format!("lp-{tag}-{k}"))),
                    ("venue", s(pool.venue.as_str())),
                    ("base", s(base)),
                    ("quote", s(quote)),
                    ("interval_ms", V::Int(5000)),
                    (
                        "inventory",
                        inventory(vec![
                            (base.to_owned(), amount(deposit, pb)),
                            (quote.to_owned(), amount(deposit, pq)),
                        ]),
                    ),
                    (
                        "strategy",
                        V::Table(vec![
                            ("kind", s("clmm-range")),
                            ("width_bps", V::Int(width)),
                            ("recenter_bps", V::Int(recenter)),
                            ("position_usd", s((d(position) * capital).to_string())),
                        ]),
                    ),
                ]);
            }
            if k < usize::from(arbs) {
                let threshold = [10, 15, 20][k] + if quote == "USDC" { 0 } else { 5 };
                rows.push(vec![
                    ("name", s(format!("arb-{tag}-{k}"))),
                    ("venue", s(pool.venue.as_str())),
                    ("base", s(base)),
                    ("quote", s(quote)),
                    ("interval_ms", V::Int([2000, 2500, 3000][k])),
                    (
                        "inventory",
                        inventory(vec![
                            (base.to_owned(), amount(d(11000) * capital, pb)),
                            (quote.to_owned(), amount(d(11000) * capital, pq)),
                        ]),
                    ),
                    (
                        "strategy",
                        V::Table(vec![
                            ("kind", s("pool-arb")),
                            ("threshold_bps", V::Int(threshold)),
                            (
                                "max_trade_usd",
                                s((d([3000, 2000, 1500][k]) * capital).to_string()),
                            ),
                        ]),
                    ),
                ]);
            }
        }
    }
    Ok(rows)
}

fn bots(spec: &Spec, prices: &Prices) -> Result<Vec<Row>, String> {
    let non_usdc: Vec<&str> = spec
        .all_tokens()
        .into_iter()
        .filter(|t| *t != "USDC")
        .collect();
    let mut rows = Vec::new();
    for k in 0..spec.arb.bots as usize {
        let (min_profit, max_trade, legs) = BOT_PARAMS[k % BOT_PARAMS.len()];
        let (fee, latency) = BOT_PROFILES[k % BOT_PROFILES.len()];
        let mut starts = vec!["USDC"];
        for j in 0..k % 3 {
            let token = non_usdc[(k + j) % non_usdc.len()];
            if !starts.contains(&token) {
                starts.push(token);
            }
        }
        let mut held = Vec::new();
        for t in &starts {
            held.push((
                (*t).to_owned(),
                amount(Decimal::from(20000), price_of(prices, t)?),
            ));
        }
        rows.push(vec![
            ("name", s(format!("searcher-{k}"))),
            (
                "start_tokens",
                V::List(starts.iter().map(|t| s(*t)).collect()),
            ),
            ("max_legs", V::Int(legs)),
            ("min_profit_usd", s(min_profit)),
            ("max_trade_usd", s(max_trade)),
            ("leg_slippage_bps", V::Int(5)),
            ("inventory", inventory(held)),
            ("sol", s("3")),
            ("priority_fee_lamports", V::Int(fee as i64)),
            ("latency_ms", V::Int(latency as i64)),
        ]);
    }
    Ok(rows)
}

fn flow(spec: &Spec, prices: &Prices) -> Result<Row, String> {
    let t = &spec.takers;
    let tokens = spec.all_tokens();
    let mut held = Vec::new();
    for (token, fixed) in [("JUP", "60000"), ("RAY", "8000"), ("USDC", "25000")] {
        if tokens.contains(&token) {
            held.push((token.to_owned(), fixed.to_owned()));
        }
    }
    for token in spec.extra_tokens() {
        held.push((
            token.to_owned(),
            amount(Decimal::from(5000), price_of(prices, token)?),
        ));
    }
    let pairs = spec
        .pairs()
        .into_iter()
        .map(|(a, b)| V::List(vec![s(a), s(b)]))
        .collect();
    Ok(vec![
        ("takers", V::Int(i64::from(t.count))),
        (
            "rate_per_min",
            V::Float(t.trades_per_min * f64::from(t.count)),
        ),
        ("median_usd", V::Float(t.median_usd)),
        ("sigma", V::Float(t.sigma)),
        ("large_probability", V::Float(t.large_probability)),
        ("large_multiplier", V::Float(t.large_multiplier)),
        ("exact_out_probability", V::Float(t.exact_out_probability)),
        ("slippage_bps", V::Int(i64::from(t.slippage_bps))),
        ("pairs", V::List(pairs)),
        ("inventory", inventory(held)),
        ("sol", s(spec.taker_sol().to_string())),
        ("refill_below_ratio", s("0.25")),
        ("rng_seed", V::Int(7)),
    ])
}

/// The overlay for `spec`, layered as `MTM_PROFILE=<profile>,scale-<name>`.
pub fn overlay(name: &str, spec: &Spec, prices: &Prices) -> Result<Rendered, String> {
    spec.check()?;
    let pools = spec.pools();
    let makers = makers(spec, &pools, prices)?;
    let bots = bots(spec, prices)?;
    let tokens = spec.all_tokens();
    let participants = spec.takers.count + spec.arb.bots + makers.len() as u32;
    let mut out = String::new();
    out.push_str(HEADER);
    out.push('\n');
    out.push_str(SPEC_PREFIX);
    out.push_str(&serde_json::to_string(spec).map_err(|e| e.to_string())?);
    out.push('\n');
    out.push_str(&format!(
        "# scale-{name}: {} takers, {} arb bots, {} makers, {} assets, {} pools\n",
        spec.takers.count,
        spec.arb.bots,
        makers.len(),
        tokens.len(),
        pools.len()
    ));
    out.push_str(&format!(
        "# ({participants} participants); maker capital ×{}. Layer: MTM_PROFILE=scenario-local,scale-{name}\n\n",
        spec.capital()
    ));
    if spec.redefines_tokens() {
        let non_usdc: Vec<&str> = tokens.iter().copied().filter(|t| *t != "USDC").collect();
        if !spec.extra_tokens().is_empty() {
            // Thin Binance books (e.g. RENDER) can go >30 s without a top-of-book change.
            table(
                &mut out,
                "scenario",
                &vec![("max_price_age_ms", V::Int(120000))],
            );
        }
        let underlyings: Vec<Row> = non_usdc
            .iter()
            .map(|t| {
                vec![
                    ("symbol", s(format!("{t}/USDT"))),
                    ("binance_symbol", s(format!("{t}USDT"))),
                ]
            })
            .collect();
        array_table(&mut out, "oracle.underlyings", &underlyings);
        let mut instruments: Vec<Row> = non_usdc
            .iter()
            .map(|t| {
                vec![
                    ("symbol", s(format!("{t}/USD"))),
                    (
                        "base",
                        V::Table(vec![
                            ("kind", s("underlying")),
                            ("feed", s(format!("{t}/USDT"))),
                        ]),
                    ),
                ]
            })
            .collect();
        instruments.push(vec![
            ("symbol", s("USDC/USD")),
            (
                "base",
                V::Table(vec![("kind", s("peg")), ("target", s("1.0000"))]),
            ),
        ]);
        array_table(&mut out, "oracle.instruments", &instruments);
        let token_rows: Vec<Row> = tokens
            .iter()
            .map(|t| {
                vec![
                    ("name", s(*t)),
                    ("mint_env", s(format!("PUBKEY_TOKEN_{t}_MINT"))),
                    ("oracle_symbol", s(format!("{t}/USD"))),
                ]
            })
            .collect();
        array_table(&mut out, "scenario.tokens", &token_rows);
    }
    let pool_rows: Vec<Row> = pools
        .iter()
        .map(|p| {
            vec![
                ("venue", s(p.venue.as_str())),
                ("base", s(p.base.clone())),
                ("quote", s(p.quote.clone())),
            ]
        })
        .collect();
    array_table(&mut out, "scenario.pools", &pool_rows);
    array_table(&mut out, "scenario.makers", &makers);
    table(&mut out, "scenario.flow", &flow(spec, prices)?);
    array_table(&mut out, "scenario.arb.bots", &bots);
    Ok(Rendered {
        toml: out,
        participants,
    })
}

/// The spec an overlay was generated from (its second line), if any.
pub fn spec_of(overlay: &str) -> Option<Spec> {
    let line = overlay.lines().nth(1)?;
    serde_json::from_str(line.strip_prefix(SPEC_PREFIX)?).ok()
}

/// Token bootstrap config (`bootstrap/tokens/deploy.ts --config`) for the
/// whole catalog: minting a token the scenario does not use is harmless.
pub fn tokens_config() -> String {
    #[derive(serde::Serialize)]
    #[serde(rename_all = "camelCase")]
    struct Entry {
        mainnet_pubkey: &'static str,
        mint_authority: &'static str,
        freeze_authority: &'static str,
        metadata_authority: &'static str,
        mint: String,
    }
    let entries: Vec<Entry> = CATALOG
        .iter()
        .map(|(token, mainnet)| Entry {
            mainnet_pubkey: mainnet,
            mint_authority: "KEYPAIR_TOKEN_MINT_AUTHORITY",
            freeze_authority: "KEYPAIR_TOKEN_FREEZE_AUTHORITY",
            metadata_authority: "KEYPAIR_TOKEN_METADATA_AUTHORITY",
            mint: format!("KEYPAIR_TOKEN_{token}_MINT"),
        })
        .collect();
    serde_json::to_string_pretty(&entries).unwrap_or_default() + "\n"
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;
    use crate::{preset, presets};

    pub(crate) fn prices() -> Prices {
        [
            ("JUP", "0.32"),
            ("RAY", "1.84"),
            ("BONK", "0.0000171"),
            ("WIF", "0.62"),
            ("PYTH", "0.11"),
            ("JTO", "1.21"),
            ("ORCA", "1.6"),
            ("RENDER", "2.9"),
            ("W", "0.07"),
            ("TNSR", "0.14"),
        ]
        .into_iter()
        .map(|(t, p)| (t.to_owned(), p.parse().expect("price")))
        .collect()
    }

    #[test]
    fn amounts_keep_three_significant_figures() {
        let px = |p: &str| p.parse::<Decimal>().expect("price");
        assert_eq!(amount(Decimal::from(22000), px("0.32")), "68800");
        assert_eq!(amount(Decimal::from(20000), Decimal::ONE), "20000");
        assert_eq!(amount(Decimal::from(5000), px("0.0000171")), "292000000");
        assert_eq!(amount(Decimal::from(560), px("1.84")), "304");
        assert_eq!(amount(Decimal::from(1), px("3")), "0.333");
    }

    #[test]
    fn every_preset_renders_and_round_trips_its_spec() {
        for (name, spec) in presets() {
            let out = overlay(name, &spec, &prices()).unwrap_or_else(|e| panic!("{name}: {e}"));
            assert_eq!(spec_of(&out.toml).as_ref(), Some(&spec), "{name}");
        }
    }

    #[test]
    fn a_missing_price_is_an_error() {
        let spec = preset("assets").expect("preset");
        let mut partial = prices();
        partial.remove("TNSR");
        assert!(overlay("assets", &spec, &partial).is_err());
    }
}
